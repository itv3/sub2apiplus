#!/usr/bin/env python3
"""缺口措辞词表——`spec_status.py` 与 `check_gaps.py` **共用**。

为什么要抽出来
--------------
两个脚本各维护一份正则时必然漂移：`spec_status.PARTIAL_RE` 认的措辞
`check_gaps.GAP_RE` 不认，于是同一条规则在状态表里已降为"部分"，
缺口表却不报它漏列——**正向的"漏列即非零退出"被削弱**。

改动规则：**只在这里加词**，两个脚本自动同步。
"""
from __future__ import annotations
import re

# 表示"这条规则还有分支/范围没覆盖，或证据支撑不了完整结论"的措辞。
# ⚠ 使用时必须限定在**同一行**内匹配（`[^\n]*`），跨行会误命中相邻句子。
GAP_PHRASES = [
    # —— 分支/范围未覆盖 ——
    "未覆盖", "仍仅有", "尚未", "未触发", "不可用于", "未在采集", "部分验证",
    "仍未观测", "未观测到", "只覆盖", "分支未采", "只验了负向", "该分支未采",
    "只采到第一跳", "三项待重判", "待重判",
    # —— 证据强度不足 ——
    "缺 wire", "观测下界", "支撑不了", "样本量偏小", "不能当完整计数",
    "无法从归档复验", "不是字段全集", "有限负例", "仅为推断",
    "仅可支持正例", "仅支持正例", "只能支持正例",
    # ⚠ **"不洁净"不进降级词表**：多数条目只是标注某个**辅助**样本不洁净，
    #    主证据仍是洁净的（如 H2-002~007 的 relay-h2 只作正例佐证）。
    #    真正影响结论的场合，正文会同时写"仅可支持正例"或"支撑不了"，
    #    那两个词已在表内。但 check_gaps 仍要登记它（见 GAP_ONLY）。
    # —— 结论已作废/需重采 ——
    "已作废", "需重采", "不得引用",
    # —— 平台/配置限定 ——
    # ⚠ 只收"限定导致结论不完整"的说法。像"适用条件"、"范围限定为"这类
    #    是**正常的规则表述**（几乎每条都有），收进来会把半数条目误降级。
    "不能推广到", "仅限 Linux", "前提是默认配置",
    # —— 自陈需降级 ——
    "只能算部分验证", "应降为部分", "未逐行核",
    # —— 结构性（仅 check_gaps 用，不参与 spec_status 降级判定）——
]

# check_gaps 额外关心的措辞：结构性不可达也该登记进缺口表，
# 但它对应"验不了"而非"部分验证"，故不参与 spec_status 的降级判定。
GAP_ONLY = [
    "结构性不可达", "无形态可对齐", "官方没有这个端点", "适用条件", "不洁净",
    # 双证据复核中的结构性／受控边界；只进入缺口总表，不改变 wire 规则总体状态。
    "抓包有限", "没有向生产上游发送", "不能证明内部调用顺序",
]

# 供 check_gaps 用：宽松匹配（整行任意位置）
GAP_RE = re.compile("|".join(re.escape(w) for w in GAP_PHRASES + GAP_ONLY))

# 供 spec_status 用：要求同一行内出现，避免跨行误命中
PARTIAL_RE = re.compile(
    r"[^\n]*(?:" + "|".join(re.escape(w) for w in GAP_PHRASES) + r")")
